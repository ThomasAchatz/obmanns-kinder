end
$$;

-- Alles für die Spielseite: Spieler, Status und (wenn man fertig ist) die Fragen mit Lösungen
create or replace function public.game_details(p_game_id bigint)
returns jsonb
language plpgsql stable security definer set search_path = public
as $$
declare
  v_me       uuid := auth.uid();
  v_game     public.games;
  v_mine     public.game_players;
  v_reveal   boolean;
  v_creator_done boolean;
begin
  select * into v_game from public.games where id = p_game_id;
  select * into v_mine from public.game_players where game_id = p_game_id and user_id = v_me;
  if v_game.id is null or v_mine.user_id is null then
    raise exception 'Spiel nicht gefunden.';
  end if;

  v_reveal := v_mine.status = 'done' or v_game.status <> 'open';
  select status = 'done' into v_creator_done from public.game_players where game_id = p_game_id and user_id = v_game.created_by;

  return jsonb_build_object(
    'id', v_game.id,
    'mode', v_game.mode,
    'status', v_game.status,
    'created_at', v_game.created_at,
    'finished_at', v_game.finished_at,
    'created_by', v_game.created_by,
    'category', (select jsonb_build_object('name', c.name, 'icon', c.icon) from public.categories c where c.id = v_game.category_id),
    'my_status', v_mine.status,
    'can_play', v_mine.status = 'pending' and v_game.status = 'open'
                and (v_game.mode <> 'duel' or v_game.created_by = v_me or v_creator_done),
    'started', exists (select 1 from public.answers where game_id = p_game_id and user_id = v_me),
    'joker_used', v_mine.joker_used,
    'can_nudge', v_mine.status = 'done' and v_game.status = 'open'
                 and (v_mine.last_nudge_at is null or v_mine.last_nudge_at <= now() - interval '20 hours')
                 and exists (select 1 from public.game_players where game_id = p_game_id and status = 'pending'),
    'can_close', v_game.mode = 'challenge' and v_game.status = 'open' and (v_game.created_by = v_me or public.is_admin()),
    'players', (
      select jsonb_agg(jsonb_build_object(
               'user_id', gp.user_id,
               'display_name', p.display_name,
               'status', gp.status,
               'score', case when v_reveal and gp.status = 'done' then gp.score end,
               'total_ms', case when v_reveal and gp.status = 'done' then gp.total_ms end,
               'rank', case when v_reveal and gp.status = 'done'
                            then (select count(*) + 1 from public.game_players o
                                   where o.game_id = gp.game_id and o.status = 'done'
                                     and (o.score > gp.score or (o.score = gp.score and o.total_ms < gp.total_ms))) end
             ) order by (gp.status = 'done') desc, gp.score desc, gp.total_ms, p.display_name)
        from public.game_players gp
        join public.profiles p on p.id = gp.user_id
       where gp.game_id = p_game_id
    ),
    -- Pro Position die Frage, die ICH bekommen habe (ggf. Ersatzfrage); Antworten der anderen
    -- nur dort, wo sie dieselbe Frage hatten.
    'questions', case when not v_reveal then '[]'::jsonb else (
      select coalesce(jsonb_agg(jsonb_build_object(
               'position', x.position,
               'question_id', q.id,
               'substitute', x.substitute,
               'text', q.text,
               'image_path', q.image_path,
               'category', jsonb_build_object('name', c.name, 'icon', c.icon),
               'author', au.display_name,
               'explanation', q.explanation,
               'source_url', q.source_url,
               'options', (select jsonb_agg(case o when 0 then q.correct when 1 then q.wrong_1 when 2 then q.wrong_2 else q.wrong_3 end order by ord)
                             from unnest(x.answer_order) with ordinality as t(o, ord)),
               'correct_index', array_position(x.answer_order, 0::smallint) - 1,
               'my_vote', (select vote from public.question_votes v where v.question_id = q.id and v.user_id = v_me),
               'answers', (
                 select coalesce(jsonb_object_agg(a.user_id, jsonb_build_object(
                          'chosen', a.chosen, 'is_correct', a.is_correct, 'ms', a.ms, 'joker', a.joker,
                          'chosen_text', case when a.chosen is null then null else
                            (case a.answer_order[a.chosen + 1] when 0 then q.correct when 1 then q.wrong_1 when 2 then q.wrong_2 else q.wrong_3 end) end
                        )), '{}'::jsonb)
                   from public.answers a
                   join public.game_players gp2 on gp2.game_id = a.game_id and gp2.user_id = a.user_id and gp2.status = 'done'
                  where a.game_id = x.game_id and a.position = x.position and a.question_id = q.id
               )
             ) order by x.position), '[]'::jsonb)
        from (
          select gq.game_id, gq.position,
                 coalesce(ma.question_id, gq.question_id) as qid,
                 coalesce(ma.answer_order, gq.answer_order) as answer_order,
                 coalesce(ma.question_id <> gq.question_id, false) as substitute
            from public.game_questions gq
            left join public.answers ma on ma.game_id = gq.game_id and ma.position = gq.position and ma.user_id = v_me
           where gq.game_id = p_game_id
        ) x
        join public.questions q on q.id = x.qid
        join public.categories c on c.id = q.category_id
        join public.profiles au on au.id = q.author_id
    ) end
  );
end
$$;

-- Übersicht für den Start-Tab
create or replace function public.my_games()
returns jsonb
language sql stable security definer set search_path = public
as $$
  select coalesce(jsonb_agg(row_to_json(x)::jsonb order by x.sort_at desc), '[]'::jsonb)
    from (
      select g.id, g.mode, g.status, g.created_at, g.finished_at, g.created_by,
             coalesce(g.finished_at, g.created_at) as sort_at,
             mine.status as my_status,
             (mine.status = 'pending' and g.status = 'open'
               and (g.mode <> 'duel' or g.created_by = auth.uid()
                    or exists (select 1 from public.game_players c where c.game_id = g.id and c.user_id = g.created_by and c.status = 'done'))) as my_turn,
             (mine.status = 'done' and g.status = 'open'
               and (mine.last_nudge_at is null or mine.last_nudge_at <= now() - interval '20 hours')) as can_nudge,
             (select jsonb_build_object('name', c.name, 'icon', c.icon) from public.categories c where c.id = g.category_id) as category,
             (select jsonb_agg(jsonb_build_object(
                       'user_id', gp.user_id,
                       'display_name', p.display_name,
                       'status', gp.status,
                       'score', case when mine.status = 'done' or g.status <> 'open' then gp.score end,
                       'total_ms', case when mine.status = 'done' or g.status <> 'open' then gp.total_ms end
                     ) order by gp.user_id = g.created_by desc, p.display_name)
                from public.game_players gp join public.profiles p on p.id = gp.user_id
               where gp.game_id = g.id) as players
        from public.games g
        join public.game_players mine on mine.game_id = g.id and mine.user_id = auth.uid()
       where (g.mode <> 'solo' or g.status = 'open')
         and (g.status = 'open' or g.finished_at > now() - interval '30 days')
       order by coalesce(g.finished_at, g.created_at) desc
       limit 60
    ) x
$$;

-- Rangliste: 'month' (aktueller oder angegebener Monat) oder 'all'
create or replace function public.leaderboard(p_period text default 'month', p_month date default null)
returns table (user_id uuid, display_name text, points integer, wins integer, games integer, correct_rate numeric)
language plpgsql stable security definer set search_path = public
as $$
declare
  v_from timestamptz;
  v_to   timestamptz;
begin
  if p_period = 'month' then
    v_from := date_trunc('month', coalesce(p_month::timestamptz, now()));
    v_to   := v_from + interval '1 month';
  end if;

  return query
  with ranks as (
    select * from public._game_ranks(v_from, v_to)
  ),
  ans as (
    select a.user_id, count(*) filter (where a.is_correct) as ok, count(*) as total
      from public.answers a
      join public.games g on g.id = a.game_id
     where a.answered_at is not null
       and g.mode <> 'solo'
       and (v_from is null or a.answered_at >= v_from)
       and (v_to is null or a.answered_at < v_to)
     group by a.user_id
  )
  select p.id,
         p.display_name,
         coalesce(sum(r.points), 0)::integer,
         coalesce(count(*) filter (where r.rnk = 1 and r.points >= 3), 0)::integer,
         coalesce(count(r.game_id), 0)::integer,
         round(coalesce(max(ans.ok)::numeric / nullif(max(ans.total), 0), 0) * 100, 0)
    from public.profiles p
    left join ranks r on r.user_id = p.id
    left join ans on ans.user_id = p.id
   group by p.id, p.display_name
   order by 3 desc, 4 desc, 6 desc, 2;
end
$$;

-- Trefferquote pro Kategorie (alle Modi)
create or replace function public.category_stats(p_user_id uuid default null)
returns table (category_id smallint, name text, icon text, answered integer, correct integer, rate numeric)
language sql stable security definer set search_path = public
as $$
  select c.id, c.name, c.icon,
         count(a.*)::integer,
         count(a.*) filter (where a.is_correct)::integer,
         round(100.0 * count(a.*) filter (where a.is_correct) / nullif(count(a.*), 0), 0)
    from public.categories c
    left join public.questions q on q.category_id = c.id
    left join public.answers a on a.question_id = q.id
                               and a.user_id = coalesce(p_user_id, auth.uid()) and a.answered_at is not null
   group by c.id, c.name, c.icon, c.sort_order
   order by c.sort_order, c.name
$$;

-- Beste Spieler je Kategorie (mind. 5 beantwortete Fragen)
create or replace function public.category_leaders()
returns table (category_id smallint, name text, icon text, user_id uuid, display_name text, answered integer, rate numeric)
language sql stable security definer set search_path = public
as $$
  with per as (
    select q.category_id, a.user_id,
           count(*) as answered,
           100.0 * count(*) filter (where a.is_correct) / count(*) as rate
      from public.answers a
      join public.questions q on q.id = a.question_id
     where a.answered_at is not null
     group by q.category_id, a.user_id
    having count(*) >= 5
  ),
  best as (
    select per.*, row_number() over (partition by per.category_id order by per.rate desc, per.answered desc) as rn
      from per
  )
  select c.id, c.name, c.icon, b.user_id, p.display_name, b.answered::integer, round(b.rate, 0)
    from public.categories c
    left join best b on b.category_id = c.id and b.rn = 1
    left join public.profiles p on p.id = b.user_id
   order by c.sort_order, c.name
$$;

-- Statistik zu den eigenen Fragen
create or replace function public.my_question_stats()
returns table (question_id bigint, plays integer, correct_rate numeric, upvotes integer, downvotes integer, open_reports integer)
language sql stable security definer set search_path = public
as $$
  select q.id,
         (select count(*) from public.answers a where a.question_id = q.id and a.answered_at is not null)::integer,
         (select round(100.0 * count(*) filter (where a.is_correct) / nullif(count(*), 0), 0)
            from public.answers a where a.question_id = q.id and a.answered_at is not null),
         (select count(*) from public.question_votes v where v.question_id = q.id and v.vote = 1)::integer,
         (select count(*) from public.question_votes v where v.question_id = q.id and v.vote = -1)::integer,
         (select count(*) from public.question_reports r where r.question_id = q.id and r.status = 'offen')::integer
    from public.questions q
   where q.author_id = auth.uid() and q.deleted_at is null
$$;

-- Wie viele aktive Fragen gibt es pro Kategorie (zeigt, wo Fragen fehlen)
create or replace function public.question_counts()
returns table (category_id smallint, name text, icon text, total integer, mine integer)
language sql stable security definer set search_path = public
as $$
  select c.id, c.name, c.icon,
         count(q.id)::integer,
         count(q.id) filter (where q.author_id = auth.uid())::integer
    from public.categories c
    left join public.questions q on q.category_id = c.id and q.is_active and q.deleted_at is null
   group by c.id, c.name, c.icon, c.sort_order
   order by c.sort_order, c.name
$$;

-- Frage löschen: schon gespielte Fragen werden nur ausgeblendet, damit alte Spiele lesbar bleiben
create or replace function public.delete_question(p_question_id bigint)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_author uuid;
begin
  select author_id into v_author from public.questions where id = p_question_id;
  if v_author is null then
    raise exception 'Frage nicht gefunden.';
  end if;
  if v_author <> auth.uid() and not public.is_admin() then
    raise exception 'Du kannst nur deine eigenen Fragen löschen.';
  end if;
  if exists (select 1 from public.game_questions where question_id = p_question_id)
     or exists (select 1 from public.answers where question_id = p_question_id) then
    update public.questions set is_active = false, deleted_at = now() where id = p_question_id;
  else
    delete from public.questions where id = p_question_id;
  end if;
end
$$;

-- Push-Abo speichern (ein Gerät gehört immer dem zuletzt angemeldeten Spieler)
create or replace function public.save_push_subscription(p_endpoint text, p_p256dh text, p_auth text)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Nicht angemeldet';
  end if;
  insert into public.push_subscriptions (user_id, endpoint, p256dh, auth)
  values (auth.uid(), p_endpoint, p_p256dh, p_auth)
  on conflict (endpoint) do update
    set user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth, created_at = now();
end
$$;

create or replace function public.delete_push_subscription(p_endpoint text)
returns void
language sql security definer set search_path = public
as $$
  delete from public.push_subscriptions where endpoint = p_endpoint and user_id = auth.uid()
$$;

-- Monatsabschluss (läuft per pg_cron am 1. jedes Monats)
create or replace function public.close_month(p_month date default null)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_month  date := coalesce(p_month, (date_trunc('month', now()) - interval '1 month')::date);
  v_label  text;
  v_winner record;
  r        record;
begin
  delete from public.monthly_results where month = v_month;

  insert into public.monthly_results (month, user_id, points, wins, games, rank)
  select v_month, l.user_id, l.points, l.wins, l.games,
         rank() over (order by l.points desc, l.wins desc)
    from public.leaderboard('month', v_month) l
   where l.games > 0;

  v_label := (array['Januar','Februar','März','April','Mai','Juni','Juli','August','September','Oktober','November','Dezember'])[extract(month from v_month)::int];

  select p.display_name, m.points into v_winner
    from public.monthly_results m join public.profiles p on p.id = m.user_id
   where m.month = v_month and m.rank = 1
   order by p.display_name limit 1;

  for r in
    select p.id, m.rank from public.profiles p
      left join public.monthly_results m on m.user_id = p.id and m.month = v_month
  loop
    perform public.send_push(
      array[r.id],
      'Monatswertung ' || v_label,
      case
        when v_winner.display_name is null then 'Im ' || v_label || ' wurde kein Duell gespielt. Zeit für eine Revanche!'
        when r.rank = 1 then 'Du bist Monatssieger mit ' || v_winner.points || ' Punkten!'
        when r.rank is not null then v_winner.display_name || ' gewinnt mit ' || v_winner.points || ' Punkten. Du bist auf Platz ' || r.rank || '.'
        else v_winner.display_name || ' gewinnt mit ' || v_winner.points || ' Punkten. Diesen Monat bist du wieder dabei!'
      end,
      '/#/profil');
  end loop;
end
$$;

