-- Wählt Fragen aus: keine Fragen der ausgeschlossenen Autoren, für die Spieler
-- ungesehene zuerst, schlecht bewertete zuletzt. Ohne Kategorie: pro Kategorie
-- die beste Frage, damit möglichst 5 verschiedene Kategorien drankommen.
create or replace function public._pick_questions(
  p_seen_by uuid[], p_exclude_authors uuid[], p_category smallint, p_count int, p_exclude_ids bigint[] default '{}')
returns table (question_id bigint)
language sql volatile security definer set search_path = public
as $$
  with eligible as (
    select q.id,
           q.category_id,
           (select max(a.shown_at) from public.answers a
             where a.question_id = q.id and a.user_id = any (p_seen_by)) as last_seen,
           coalesce((select sum(v.vote) from public.question_votes v where v.question_id = q.id), 0) as votes,
           random() as r
      from public.questions q
     where q.is_active
       and q.deleted_at is null
       and q.author_id <> all (coalesce(p_exclude_authors, '{}'))
       and q.id <> all (coalesce(p_exclude_ids, '{}'))
       and (p_category is null or q.category_id = p_category)
  ),
  ranked as (
    select e.*,
           row_number() over (
             partition by e.category_id
             order by (e.last_seen is not null), (e.votes <= -3), e.last_seen nulls first, e.r
           ) as rn
      from eligible e
  )
  select id
    from ranked
   order by rn, (last_seen is not null), (votes <= -3), r
   limit p_count
$$;

create or replace function public._shuffled_order()
returns smallint[]
language sql volatile
as $$
  select array_agg(x order by random()) from unnest('{0,1,2,3}'::smallint[]) as x
$$;

-- Neues Spiel anlegen: 'solo' (mit Kategorie), 'duel' (1 Gegner), 'challenge' (mehrere)
create or replace function public.create_game(p_mode text, p_category_id smallint default null, p_invitees uuid[] default '{}')
returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  v_me      uuid := auth.uid();
  v_players uuid[];
  v_game    bigint;
  v_ids     bigint[];
  v_name    text;
begin
  if v_me is null then
    raise exception 'Nicht angemeldet';
  end if;

  p_invitees := coalesce(array(select distinct u from unnest(coalesce(p_invitees, '{}')) u where u <> v_me), '{}');

  if p_mode = 'solo' then
    if p_category_id is null then
      raise exception 'Bitte wähle eine Kategorie.';
    end if;
    p_invitees := '{}';
  elsif p_mode = 'duel' then
    if cardinality(p_invitees) <> 1 then
      raise exception 'Ein Duell braucht genau einen Gegner.';
    end if;
    p_category_id := null;
  elsif p_mode = 'challenge' then
    if cardinality(p_invitees) < 1 then
      raise exception 'Wähle mindestens eine Person für die Challenge.';
    end if;
    p_category_id := null;
  else
    raise exception 'Unbekannter Spielmodus: %', p_mode;
  end if;

  if (select count(*) from public.profiles where id = any (p_invitees)) <> cardinality(p_invitees) then
    raise exception 'Mindestens ein Mitspieler existiert nicht.';
  end if;

  v_players := array[v_me] || p_invitees;

  -- Zuerst Fragen, die keiner der Mitspieler geschrieben hat
  v_ids := array(select question_id from public._pick_questions(v_players, v_players, p_category_id, 5));
  -- Reicht das nicht (z. B. Challenge mit allen), dürfen auch Fragen von Mitspielern dran;
  -- deren Autor bekommt an dieser Stelle später eine Ersatzfrage.
  if p_mode <> 'solo' and cardinality(v_ids) < 5 then
    v_ids := v_ids || array(select question_id from public._pick_questions(v_players, '{}', null, 5 - cardinality(v_ids), v_ids));
  end if;
  if cardinality(v_ids) < 5 then
    raise exception 'Es gibt nur % passende Fragen, für ein Spiel braucht es 5. Ladet mehr Fragen hoch!', cardinality(v_ids);
  end if;

  insert into public.games (mode, category_id, created_by)
  values (p_mode, p_category_id, v_me)
  returning id into v_game;

  insert into public.game_questions (game_id, position, question_id, answer_order)
  select v_game, (row_number() over (order by random()))::smallint, id, public._shuffled_order()
    from unnest(v_ids) as id;

  insert into public.game_players (game_id, user_id)
  select v_game, unnest(v_players);

  if p_mode = 'challenge' then
    select display_name into v_name from public.profiles where id = v_me;
    perform public.send_push(p_invitees, 'Neue Gruppen-Challenge',
      v_name || ' fordert dich heraus. 5 Fragen warten auf dich.', '/#/spiel/' || v_game);
  end if;

  return v_game;
end
$$;

-- Wertet ein Spiel aus: Rang je Spieler und Punkte für die Rangliste
create or replace function public._game_ranks(p_from timestamptz default null, p_to timestamptz default null)
returns table (game_id bigint, mode text, finished_at timestamptz, user_id uuid, score smallint, total_ms integer, rnk bigint, points integer)
language sql stable security definer set search_path = public
as $$
  with done as (
    select g.id as game_id, g.mode, g.finished_at, gp.user_id, gp.score, gp.total_ms,
           rank() over (partition by g.id order by gp.score desc, gp.total_ms asc) as rnk,
           count(*) over (partition by g.id) as n_done
      from public.games g
      join public.game_players gp on gp.game_id = g.id and gp.status = 'done'
     where g.mode in ('duel', 'challenge')
       and g.status in ('finished', 'closed')
       and (p_from is null or g.finished_at >= p_from)
       and (p_to is null or g.finished_at < p_to)
  ),
  tied as (
    select d.*, count(*) over (partition by d.game_id, d.rnk) as n_same
      from done d
  )
  select game_id, mode, finished_at, user_id, score, total_ms, rnk,
         case
           when n_done < 2 then 0
           when mode = 'duel' and rnk = 1 and n_same = 1 then 3
           when mode = 'duel' and rnk = 1 then 1
           when mode = 'challenge' and rnk = 1 then 3
           when mode = 'challenge' and rnk = 2 then 2
           when mode = 'challenge' and rnk = 3 then 1
           else 0
         end::integer as points
    from tied
$$;

-- Spieler hat alle 5 Fragen beantwortet
create or replace function public._finish_player(p_game_id bigint, p_user uuid)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_game    public.games;
  v_name    text;
  v_pending int;
  r         record;
  v_total   int;
  v_text    text;
begin
  update public.game_players gp
     set status = 'done',
         finished_at = now(),
         score = (select count(*) from public.answers a where a.game_id = p_game_id and a.user_id = p_user and a.is_correct),
         total_ms = (select coalesce(sum(a.ms), 0) from public.answers a where a.game_id = p_game_id and a.user_id = p_user)
   where gp.game_id = p_game_id and gp.user_id = p_user;

  select * into v_game from public.games where id = p_game_id;
  select display_name into v_name from public.profiles where id = p_user;
  select count(*) into v_pending from public.game_players where game_id = p_game_id and status = 'pending';

  if v_game.mode = 'solo' then
    update public.games set status = 'finished', finished_at = now() where id = p_game_id;
    return;
  end if;

  -- Duell: Herausforderer ist fertig → Gegner bekommt die Herausforderung
  if v_game.mode = 'duel' and p_user = v_game.created_by and v_pending > 0 then
    perform public.send_push(
      array(select user_id from public.game_players where game_id = p_game_id and user_id <> p_user),
      'Neues Duell', v_name || ' hat dich zum Duell herausgefordert.', '/#/spiel/' || p_game_id);
  end if;

  if v_pending = 0 then
    update public.games set status = 'finished', finished_at = now() where id = p_game_id and status = 'open';
    select count(*) into v_total from public.game_players where game_id = p_game_id;
    for r in
      select gr.user_id, gr.rnk, gr.score from public._game_ranks() gr where gr.game_id = p_game_id
    loop
      if r.user_id = p_user then
        continue; -- sieht das Ergebnis ohnehin gerade
      end if;
      if v_game.mode = 'duel' then
        v_text := case when r.rnk = 1 then 'Gewonnen! ' else 'Verloren. ' end
                  || 'Du hattest ' || r.score || ' von 5 richtig.';
        perform public.send_push(array[r.user_id], 'Duell gegen ' || v_name || ' ist fertig', v_text, '/#/spiel/' || p_game_id);
      else
        perform public.send_push(array[r.user_id], 'Gruppen-Challenge ist fertig',
          'Du bist auf Platz ' || r.rnk || ' von ' || v_total || '.', '/#/spiel/' || p_game_id);
      end if;
    end loop;
  end if;
end
$$;

-- Speichert eine Antwort (p_choice null = Zeit abgelaufen)
create or replace function public._record_answer(p_game_id bigint, p_user uuid, p_position smallint, p_choice smallint)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_ans     public.answers;
  v_q       public.questions;
  v_correct smallint;
  v_ms      int;
  v_ok      boolean;
begin
  select * into v_ans from public.answers
   where game_id = p_game_id and user_id = p_user and position = p_position
   for update;
  if not found or v_ans.answered_at is not null then
    raise exception 'Diese Frage ist nicht offen.';
  end if;

  select * into v_q from public.questions where id = v_ans.question_id;

  v_correct := (array_position(v_ans.answer_order, 0::smallint) - 1)::smallint;
  v_ms := least(30000, (extract(epoch from (now() - v_ans.shown_at)) * 1000)::int);

  -- 30 Sekunden + 2 Sekunden Toleranz für das Netz
  if p_choice is null or now() - v_ans.shown_at > interval '32 seconds' then
    p_choice := null;
    v_ms := 30000;
  end if;
  if p_choice is not null and v_ans.hidden is not null and p_choice = any (v_ans.hidden) then
    raise exception 'Diese Antwort wurde vom Joker ausgeblendet.';
  end if;
  v_ok := p_choice is not null and p_choice = v_correct;

  update public.answers
     set chosen = p_choice, is_correct = v_ok, ms = v_ms, answered_at = now()
   where game_id = p_game_id and user_id = p_user and position = p_position;

  if p_position = 5 then
    perform public._finish_player(p_game_id, p_user);
  end if;

  return jsonb_build_object(
    'position', p_position,
    'chosen', p_choice,
    'correct_index', v_correct,
    'is_correct', v_ok,
    'timed_out', p_choice is null,
    'explanation', v_q.explanation,
    'source_url', v_q.source_url,
    'question_id', v_q.id,
    'author', (select display_name from public.profiles where id = v_q.author_id),
    'my_vote', (select vote from public.question_votes where question_id = v_q.id and user_id = p_user),
    'finished', p_position = 5
  );
end
$$;

-- Liefert die aktuelle Frage (ohne Lösung). Startet die 30 Sekunden.
create or replace function public.next_question(p_game_id bigint)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_me     uuid := auth.uid();
  v_game   public.games;
  v_player public.game_players;
  v_ans    public.answers;
  v_pos    smallint;
  v_gq     public.game_questions;
  v_q      public.questions;
  v_order  smallint[];
  v_sub    bigint;
begin
  select * into v_game from public.games where id = p_game_id;
  if not found then
    raise exception 'Spiel nicht gefunden.';
  end if;

  select * into v_player from public.game_players
   where game_id = p_game_id and user_id = v_me
   for update;
  if not found then
    raise exception 'Du spielst in diesem Spiel nicht mit.';
  end if;
  if v_player.status = 'done' then
    return jsonb_build_object('done', true);
  end if;
  if v_game.status = 'closed' then
    raise exception 'Diese Challenge wurde schon geschlossen.';
  end if;
  if v_game.mode = 'duel' and v_game.created_by <> v_me and exists (
       select 1 from public.game_players
        where game_id = p_game_id and user_id = v_game.created_by and status <> 'done') then
    raise exception 'Dein Gegner spielt seine Fragen noch. Du bekommst einen Push, sobald du dran bist.';
  end if;

  -- Gibt es eine angezeigte, aber noch nicht beantwortete Frage?
  select * into v_ans from public.answers
   where game_id = p_game_id and user_id = v_me and answered_at is null;
  if found then
    if now() - v_ans.shown_at > interval '32 seconds' then
      perform public._record_answer(p_game_id, v_me, v_ans.position, null);
      if v_ans.position = 5 then
        return jsonb_build_object('done', true);
      end if;
    else
      v_pos := v_ans.position;
    end if;
  end if;

  if v_pos is null then
    select (coalesce(max(position), 0) + 1)::smallint into v_pos
      from public.answers where game_id = p_game_id and user_id = v_me;
    if v_pos > 5 then
      return jsonb_build_object('done', true);
    end if;

    select * into v_gq from public.game_questions where game_id = p_game_id and position = v_pos;
    select * into v_q from public.questions where id = v_gq.question_id;
    v_order := v_gq.answer_order;

    -- Eigene Frage? Dann Ersatzfrage aus derselben Kategorie (notfalls aus einer anderen)
    if v_q.author_id = v_me then
      select question_id into v_sub
        from public._pick_questions(array[v_me], array[v_me], v_q.category_id, 1,
               array(select question_id from public.game_questions where game_id = p_game_id)
               || array(select question_id from public.answers where game_id = p_game_id));
      if v_sub is null then
        select question_id into v_sub
          from public._pick_questions(array[v_me], array[v_me], null, 1,
                 array(select question_id from public.game_questions where game_id = p_game_id)
                 || array(select question_id from public.answers where game_id = p_game_id));
      end if;
      if v_sub is null then
        raise exception 'Für deine eigene Frage gibt es keine Ersatzfrage. Ladet mehr Fragen hoch!';
      end if;
      select * into v_q from public.questions where id = v_sub;
      v_order := public._shuffled_order();
    end if;

    insert into public.answers (game_id, user_id, position, question_id, answer_order)
    values (p_game_id, v_me, v_pos, v_q.id, v_order)
    returning * into v_ans;
  end if;

  select * into v_q from public.questions where id = v_ans.question_id;
  select * into v_gq from public.game_questions where game_id = p_game_id and position = v_pos;

  return jsonb_build_object(
    'done', false,
    'position', v_pos,
    'total', 5,
    'question_id', v_q.id,
    'text', v_q.text,
    'image_path', v_q.image_path,
    'category', (select jsonb_build_object('name', c.name, 'icon', c.icon) from public.categories c where c.id = v_q.category_id),
    'author', (select display_name from public.profiles where id = v_q.author_id),
    'substitute', v_ans.question_id <> v_gq.question_id,
    'options', (
      select jsonb_agg(case o when 0 then v_q.correct when 1 then v_q.wrong_1 when 2 then v_q.wrong_2 else v_q.wrong_3 end order by ord)
        from unnest(v_ans.answer_order) with ordinality as t(o, ord)
    ),
    'seconds_left', greatest(0, 30 - extract(epoch from (now() - v_ans.shown_at))),
    'joker_available', not v_player.joker_used,
    'hidden', coalesce(to_jsonb(v_ans.hidden), '[]'::jsonb)
  );
end
$$;

