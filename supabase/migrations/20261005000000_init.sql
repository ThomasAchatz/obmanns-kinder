-- Pro Spieler die tatsächlich gestellte Frage. Normalerweise die Frage aus game_questions;
-- hat der Spieler diese selbst geschrieben, bekommt er eine Ersatzfrage aus derselben Kategorie.
create table public.answers (
  game_id      bigint not null,
  user_id      uuid not null,
  position     smallint not null check (position between 1 and 5),
  question_id  bigint not null references public.questions(id),
  answer_order smallint[] not null,
  chosen      smallint check (chosen between 0 and 3),   -- Index auf dem Bildschirm, null = Zeit abgelaufen
  is_correct  boolean,
  ms          integer,
  joker       boolean not null default false,
  hidden      smallint[],                               -- vom 50:50-Joker ausgeblendete Antworten
  shown_at    timestamptz not null default now(),
  answered_at timestamptz,
  primary key (game_id, user_id, position),
  foreign key (game_id, user_id) references public.game_players (game_id, user_id) on delete cascade
);
create index answers_question_idx on public.answers (question_id);

create or replace function public.is_game_player(p_game_id bigint)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.game_players where game_id = p_game_id and user_id = auth.uid())
