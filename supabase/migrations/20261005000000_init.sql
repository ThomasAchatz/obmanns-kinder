-- 50:50-Joker: liefert die zwei ausgeblendeten falschen Antworten
create or replace function public.use_joker(p_game_id bigint, p_position smallint)
returns smallint[]
language plpgsql security definer set search_path = public
as $$
declare
  v_me     uuid := auth.uid();
  v_player public.game_players;
  v_ans    public.answers;
  v_hidden smallint[];
begin
  select * into v_player from public.game_players where game_id = p_game_id and user_id = v_me for update;
  if not found or v_player.status <> 'pending' then
    raise exception 'Du kannst in diesem Spiel keinen Joker setzen.';
  end if;
  if v_player.joker_used then
    raise exception 'Dein Joker ist für dieses Spiel schon verbraucht.';
  end if;

  select * into v_ans from public.answers
   where game_id = p_game_id and user_id = v_me and position = p_position and answered_at is null;
  if not found or now() - v_ans.shown_at > interval '30 seconds' then
    raise exception 'Die Frage ist nicht mehr offen.';
  end if;

  select array_agg(i order by i) into v_hidden
    from (select (ord - 1)::smallint as i
            from unnest(v_ans.answer_order) with ordinality as t(o, ord)
           where o <> 0
           order by random()
           limit 2) s;

  update public.answers set joker = true, hidden = v_hidden
   where game_id = p_game_id and user_id = v_me and position = p_position;
  update public.game_players set joker_used = true where game_id = p_game_id and user_id = v_me;

  return v_hidden;
end
$$;

-- Anstupsen: höchstens einmal pro Tag
create or replace function public.nudge(p_game_id bigint)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_me      uuid := auth.uid();
  v_player  public.game_players;
  v_game    public.games;
  v_pending uuid[];
  v_name    text;
begin
  select * into v_game from public.games where id = p_game_id;
  select * into v_player from public.game_players where game_id = p_game_id and user_id = v_me for update;
  if not found or v_game.status <> 'open' then
    raise exception 'Dieses Spiel ist nicht mehr offen.';
  end if;
  if v_player.status <> 'done' then
    raise exception 'Spiel erst deine eigenen Fragen.';
  end if;
  if v_player.last_nudge_at is not null and v_player.last_nudge_at > now() - interval '20 hours' then
    raise exception 'Du hast heute schon angestupst. Morgen geht es wieder.';
  end if;

  select array_agg(user_id) into v_pending from public.game_players where game_id = p_game_id and status = 'pending';
  if v_pending is null then
    raise exception 'Alle haben schon gespielt.';
  end if;

  update public.game_players set last_nudge_at = now() where game_id = p_game_id and user_id = v_me;
  select display_name into v_name from public.profiles where id = v_me;
  perform public.send_push(v_pending, 'Anstupser', v_name || ' wartet auf deinen Zug.', '/#/spiel/' || p_game_id);
end
$$;

-- Gruppen-Challenge schließen (Ersteller oder Admin)
