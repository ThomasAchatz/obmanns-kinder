-- =====================================================================
-- Push auslösen (über pg_net an die Edge Function "push")
-- =====================================================================
create or replace function public.send_push(p_user_ids uuid[], p_title text, p_body text, p_url text default '/')
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_url    text;
  v_secret text;
begin
  if p_user_ids is null or cardinality(p_user_ids) = 0 then
    return;
  end if;
  select value into v_url from public.app_config where key = 'push_url';
  select value into v_secret from public.app_config where key = 'push_secret';
  if v_url is null or v_secret is null then
    return; -- Push noch nicht eingerichtet
  end if;
  begin
    perform net.http_post(
      url     := v_url,
      body    := jsonb_build_object('user_ids', to_jsonb(p_user_ids), 'title', p_title, 'body', p_body, 'url', p_url),
      headers := jsonb_build_object('Content-Type', 'application/json', 'x-push-secret', v_secret)
    );
  exception when others then
    raise warning 'Push konnte nicht ausgelöst werden: %', sqlerrm;
  end;
end
$$;

