create table public.questions (
  id          bigint generated always as identity primary key,
  category_id smallint not null references public.categories(id),
  author_id   uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  text        text not null check (char_length(text) between 5 and 300),
  image_path  text,
  correct     text not null check (char_length(correct) between 1 and 120),
  wrong_1     text not null check (char_length(wrong_1) between 1 and 120),
  wrong_2     text not null check (char_length(wrong_2) between 1 and 120),
  wrong_3     text not null check (char_length(wrong_3) between 1 and 120),
  explanation text check (char_length(explanation) <= 500),
  source_url  text check (source_url ~* '^https?://'),
  is_active   boolean not null default true,
  deleted_at  timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint answers_distinct check (
    lower(trim(correct)) not in (lower(trim(wrong_1)), lower(trim(wrong_2)), lower(trim(wrong_3)))
    and lower(trim(wrong_1)) not in (lower(trim(wrong_2)), lower(trim(wrong_3)))
    and lower(trim(wrong_2)) <> lower(trim(wrong_3))
  )
);
create index questions_category_idx on public.questions (category_id) where is_active and deleted_at is null;
create index questions_author_idx on public.questions (author_id);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end
$$;

create trigger questions_touch before update on public.questions
  for each row execute function public.touch_updated_at();

